SPRINT = """# generated by BMad
generated: 2026-10-01
last_updated: 2026-10-01
development_status:
  epic-1: in-progress
  1-1-login: done
  1-2-logout: backlog
  1-3-profile: backlog
"""


def sh(cwd, *args):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout


def write(root, rel, text):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def commit(root, message):
    sh(root, "git", "add", "-A")
    sh(root, "git", "commit", "-qm", message)


class MergeSprintTest(unittest.TestCase):
    def test_more_advanced_status_and_later_stamp_win(self):
        ours = SPRINT.replace("1-3-profile: backlog", "1-3-profile: in-progress")
        theirs = (SPRINT.replace("last_updated: 2026-10-01", "last_updated: 2026-10-05")
                  .replace("1-2-logout: backlog", "1-2-logout: done"))
        merged, changes, warnings = land.merge_sprint(ours, theirs)
        self.assertIn("1-2-logout: done", merged)
        self.assertIn("1-3-profile: in-progress", merged)       # ours moved further
        self.assertIn("last_updated: 2026-10-05", merged)
        self.assertIn("# generated by BMad", merged)
        self.assertEqual(changes, [{"key": "1-2-logout", "from": "backlog", "to": "done"}])
        self.assertEqual(warnings, [])

    def test_keys_of_one_side_are_kept_in_place(self):
        theirs = SPRINT.replace("  1-3-profile: backlog\n", "  1-2a-split: review\n  1-3-profile: backlog\n")
        ours = SPRINT + "  1-4-avatar: backlog\n"
        merged, _, _ = land.merge_sprint(ours, theirs)
        keys = [line.split(":")[0].strip() for line in merged.split("\n") if line.startswith("  ")]
        self.assertEqual(keys, ["epic-1", "1-1-login", "1-2-logout", "1-2a-split", "1-3-profile", "1-4-avatar"])

    def test_older_stamp_of_theirs_loses(self):
        theirs = SPRINT.replace("last_updated: 2026-10-01", "last_updated: 2026-09-01")
        merged, _, _ = land.merge_sprint(SPRINT, theirs)
        self.assertIn("last_updated: 2026-10-01", merged)

    def test_stamps_compare_as_dates_with_zones(self):
        ours = SPRINT.replace("last_updated: 2026-10-01", "last_updated: 2026-10-01T12:00:00+03:00")
        later = SPRINT.replace("last_updated: 2026-10-01", "last_updated: 2026-10-01T10:00:00Z")
        earlier = SPRINT.replace("last_updated: 2026-10-01", "last_updated: 2026-10-01T10:00:00+05:00")
        self.assertIn("2026-10-01T10:00:00Z", land.merge_sprint(ours, later)[0])
        self.assertIn("2026-10-01T12:00:00+03:00", land.merge_sprint(ours, earlier)[0])
        us = SPRINT.replace("last_updated: 2026-10-01", "last_updated: 10-05-2026 09:00")
        self.assertIn("last_updated: 10-05-2026 09:00", land.merge_sprint(us, SPRINT)[0])

    def test_unparsed_stamp_keeps_ours_with_a_warning(self):
        theirs = SPRINT.replace("last_updated: 2026-10-01", "last_updated: someday")
        merged, _, warnings = land.merge_sprint(SPRINT, theirs)
        self.assertIn("last_updated: 2026-10-01", merged)
        self.assertEqual(len(warnings), 1)

    def test_trailing_comment_is_kept(self):
        ours = SPRINT.replace("1-2-logout: backlog", "1-2-logout: backlog  # owner: anna")
        theirs = SPRINT.replace("1-2-logout: backlog", "1-2-logout: done")
        self.assertIn("1-2-logout: done  # owner: anna", land.merge_sprint(ours, theirs)[0])


class RunWorktreeBase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = os.path.realpath(os.path.join(self.tmp.name, "repo"))
        os.makedirs(self.repo)
        sh(self.repo, "git", "init", "-q", "-b", "main")
        sh(self.repo, "git", "config", "user.email", "t@t")
        sh(self.repo, "git", "config", "user.name", "t")
        write(self.repo, ".gitignore", "*.user.toml\n.claude/settings.local.json\n")
        write(self.repo, SPRINT_REL, SPRINT)
        write(self.repo, "app.py", "a = 1\nb = 2\n")
        write(self.repo, ".auto-bmad.toml", '[[verify]]\nname = "project-tests"\ncommand = "true"\n')
        commit(self.repo, "init")
        write(self.repo, "_bmad/config.user.toml", "user_skill_level = 'expert'\n")
        write(self.repo, ".claude/settings.local.json", "{}\n")
        self.env = os.environ.get("AUTO_BMAD_CONFIG")
        os.environ["AUTO_BMAD_CONFIG"] = os.path.join(self.repo, "none.toml")

    def tearDown(self):
        if self.env is None:
            os.environ.pop("AUTO_BMAD_CONFIG", None)
        else:
            os.environ["AUTO_BMAD_CONFIG"] = self.env
        self.tmp.cleanup()

    def start(self, name="epic-1"):
        result, code = worktree.cmd_start(self.repo, name)
        self.assertEqual(code, 0, result)
        return result


class StartTest(RunWorktreeBase):
    def test_creates_the_worktree_with_local_files(self):
        r = self.start()
        self.assertTrue(r["created"])
        self.assertEqual(r["branch"], "bmad/epic-1")
        self.assertEqual(r["base_branch"], "main")
        self.assertTrue(r["path"].startswith(os.path.join(self.repo, ".claude", "worktrees")))
        self.assertIn("_bmad/config.user.toml", r["seeded"])
        self.assertIn(".claude/settings.local.json", r["seeded"])
        self.assertTrue(os.path.isfile(os.path.join(r["path"], ".claude", "settings.local.json")))
        self.assertEqual(r["land"], "auto-bmad land bmad/epic-1")
        self.assertEqual(sh(self.repo, "git", "status", "--porcelain"), "")    # main tree untouched
        self.assertEqual(main_tree(r["path"]), self.repo)

    def test_second_start_resumes_the_live_worktree(self):
        first = self.start()
        write(first["path"], "app.py", "a = 1\nb = 3\n")
        commit(first["path"], "work")
        again = self.start()
        self.assertTrue(again["resumed"])
        self.assertFalse(again["created"])
        self.assertEqual(again["path"], first["path"])
        self.assertEqual(len(sh(self.repo, "git", "worktree", "list").splitlines()), 2)

    def test_branch_without_a_directory_is_attached_again(self):
        first = self.start()
        write(first["path"], "app.py", "a = 1\nb = 3\n")
        commit(first["path"], "work")
        sh(self.repo, "git", "worktree", "remove", first["path"])
        again = self.start()
        self.assertTrue(again["resumed"])
        with open(os.path.join(again["path"], "app.py")) as fh:
            self.assertIn("b = 3", fh.read())

    def test_run_worktree_is_not_a_stale_story_worktree(self):
        self.start()
        self.assertEqual(worktree.cmd_list(self.repo)[0]["worktrees"], [])

    def test_events_of_the_run_go_to_the_main_tree(self):
        import ext
        wt = self.start()["path"]
        ext.log_event(wt, {"event": "run-start", "epic": 1}, [])
        self.assertTrue(os.path.isfile(os.path.join(self.repo, ".auto-bmad", "events.jsonl")))
        self.assertFalse(os.path.exists(os.path.join(wt, ".auto-bmad", "events.jsonl")))

    def test_main_tree_outside_git_is_the_path(self):
        other = os.path.join(self.tmp.name, "plain")
        os.makedirs(other)
        self.assertEqual(main_tree(other), os.path.abspath(other))

    def test_untracked_local_files_are_skipped_on_request(self):
        sh(self.repo, "git", "rm", "-q", "--cached", ".auto-bmad.toml")
        sh(self.repo, "git", "commit", "-qm", "config out of git")
        self.assertEqual(worktree.uncommitted(self.repo)[0], [".auto-bmad.toml"])
        self.assertEqual(worktree.uncommitted(self.repo, worktree.RUN_LOCAL)[0], [])
        write(self.repo, "app.py", "a = 2\n")
        self.assertEqual(worktree.uncommitted(self.repo, worktree.RUN_LOCAL)[0], ["app.py"])

    def test_bad_name(self):
        self.assertEqual(worktree.cmd_start(self.repo, "../x")[1], 1)


class LandTest(RunWorktreeBase):
    def test_clean_merge_lands_and_cleans_up(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertTrue(result["merged"])
        self.assertEqual(result["tests"]["verdict"], "pass")
        self.assertTrue(os.path.isfile(os.path.join(self.repo, "feature.py")))
        self.assertFalse(os.path.exists(wt))
        self.assertEqual(sh(self.repo, "git", "branch", "--list", "bmad/*"), "")
        parents = sh(self.repo, "git", "log", "-1", "--format=%P").split()
        self.assertEqual(len(parents), 2)

    def test_sprint_status_conflict_is_resolved(self):
        wt = self.start()["path"]
        write(wt, SPRINT_REL, SPRINT.replace("1-2-logout: backlog", "1-2-logout: done")
              .replace("last_updated: 2026-10-01", "last_updated: 2026-10-07"))
        commit(wt, "story 1-2 done")
        write(self.repo, SPRINT_REL, SPRINT.replace("1-2-logout: backlog", "1-2-logout: ready-for-dev")
              .replace("1-3-profile: backlog", "1-3-profile: in-progress"))
        commit(self.repo, "planning in main")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertEqual(result["conflicts"], [SPRINT_REL])
        with open(os.path.join(self.repo, SPRINT_REL)) as fh:
            text = fh.read()
        self.assertIn("1-2-logout: done", text)
        self.assertIn("1-3-profile: in-progress", text)
        self.assertIn("last_updated: 2026-10-07", text)
        self.assertNotIn("<<<<<<<", text)
        self.assertEqual(sh(self.repo, "git", "status", "--porcelain"), "")

    def test_code_conflict_stops_and_names_the_files(self):
        wt = self.start()["path"]
        write(wt, "app.py", "a = 1\nb = 3\n")
        commit(wt, "run edit")
        write(self.repo, "app.py", "a = 1\nb = 4\n")
        commit(self.repo, "main edit")
        head = sh(self.repo, "git", "rev-parse", "HEAD")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 2)
        self.assertEqual(result["conflicts"], ["app.py"])
        self.assertFalse(result["merged"])
        self.assertEqual(sh(self.repo, "git", "rev-parse", "HEAD"), head)
        self.assertTrue(os.path.isdir(wt))                                   # the run is kept

    def test_dirty_main_tree_is_refused(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        write(self.repo, "app.py", "a = 1\nb = 9\n")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 2)
        self.assertEqual(result["dirty"], ["app.py"])
        self.assertIn("uncommitted", result["error"])
        self.assertFalse(os.path.exists(os.path.join(self.repo, "feature.py")))

    def test_failing_tests_merge_nothing(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        write(self.repo, ".auto-bmad.toml", '[[verify]]\nname = "project-tests"\n'
                                            'command = "test ! -f feature.py"\n')
        commit(self.repo, "tests that the feature breaks")
        head = sh(self.repo, "git", "rev-parse", "HEAD")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 2, result)
        self.assertEqual(result["tests"]["verdict"], "problem")
        self.assertEqual(sh(self.repo, "git", "rev-parse", "HEAD"), head)
        self.assertEqual(sh(wt, "git", "branch", "--show-current").strip(), "bmad/epic-1")

    def test_branch_without_worktree_is_tested_in_a_temporary_one(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        sh(self.repo, "git", "worktree", "remove", wt)
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertEqual(result["tests"]["verdict"], "pass")
        self.assertEqual(len(sh(self.repo, "git", "worktree", "list").splitlines()), 1)

    def test_untracked_local_files_are_not_dirt(self):
        sh(self.repo, "git", "rm", "-q", "--cached", ".auto-bmad.toml")
        sh(self.repo, "git", "commit", "-qm", "config out of git")
        write(self.repo, "CLAUDE.local.md", "local notes\n")
        r = self.start()
        wt = r["path"]
        self.assertIn(".auto-bmad.toml", r["left_in_main"])               # not ignored: not copied
        self.assertFalse(os.path.exists(os.path.join(wt, ".auto-bmad.toml")))
        self.assertEqual(sh(wt, "git", "status", "--porcelain"), "")
        self.assertIn("?? .auto-bmad.toml", sh(self.repo, "git", "status", "--porcelain"))
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertEqual(result["tests"]["command"], "true")               # the main tree's config

    def test_start_takes_back_old_shared_excludes(self):
        exclude = os.path.join(self.repo, ".git", "info", "exclude")
        with open(exclude, "a") as fh:
            fh.write("/.auto-bmad.toml\n/CLAUDE.local.md\nmy-own-rule\n")
        r = self.start()
        self.assertEqual(sorted(r["exclude_cleaned"]), ["/.auto-bmad.toml", "/CLAUDE.local.md"])
        with open(exclude) as fh:
            text = fh.read()
        self.assertIn("my-own-rule", text)
        self.assertNotIn("/.auto-bmad.toml", text)

    def test_merged_branch_without_a_recorded_base_is_cleaned_up(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        sh(self.repo, "git", "config", "--unset", "branch.bmad/epic-1.autoBmadBaseCommit")
        sh(self.repo, "git", "merge", "-q", "--no-ff", "-m", "by hand", "bmad/epic-1")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertEqual(result["removed_branch"], "bmad/epic-1")

    def test_another_base_branch_is_refused_unless_onto_current(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        sh(self.repo, "git", "checkout", "-q", "-b", "other")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 2)
        self.assertIn("--onto-current", result["error"])
        self.assertTrue(os.path.isdir(wt))
        result, code = land.land(self.repo, "bmad/epic-1", onto_current=True)
        self.assertEqual(code, 0, result)
        self.assertIn("warning_base", result)

    def test_failed_return_to_the_branch_stops_without_cleanup(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        write(self.repo, ".auto-bmad.toml", '[[verify]]\nname = "project-tests"\n'
                                            'command = "touch \\"$(git rev-parse --git-dir)/index.lock\\""\n')
        commit(self.repo, "a test that locks the worktree index")
        head = sh(self.repo, "git", "rev-parse", "HEAD")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 1, result)
        self.assertIn("could not go back", result["error"])
        self.assertEqual(sh(self.repo, "git", "rev-parse", "HEAD"), head)
        self.assertTrue(os.path.isdir(wt))
        self.assertIn("bmad/epic-1", sh(self.repo, "git", "branch", "--list", "bmad/*"))

    def test_branch_without_work_is_not_removed(self):
        wt = self.start()["path"]
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 2)
        self.assertIn("no work", result["error"])
        self.assertTrue(os.path.isdir(wt))
        result, code = land.land(self.repo, "bmad/epic-1", force_cleanup=True)
        self.assertEqual(code, 0, result)
        self.assertFalse(os.path.exists(wt))

    def test_branch_merged_by_hand_is_only_cleaned_up(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        sh(self.repo, "git", "merge", "-q", "--no-ff", "-m", "by hand", "bmad/epic-1")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertIn("already merged", result["note"])
        self.assertEqual(result["removed_branch"], "bmad/epic-1")

    def test_failed_fast_forward_shows_what_git_says(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        write(self.repo, ".auto-bmad.toml", '[[verify]]\nname = "project-tests"\n'
                                            f'command = "git -C {self.repo} commit -q --allow-empty -m moved"\n')
        commit(self.repo, "a test that moves the main branch")
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 1, result)
        self.assertIn("git says", result["error"])
        self.assertIn("fast-forward", result["error"].lower())

    def test_worktree_directory_deleted_by_hand_is_pruned(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        import shutil
        shutil.rmtree(wt)
        result, code = land.land(self.repo, "bmad/epic-1")
        self.assertEqual(code, 0, result)
        self.assertEqual(result["removed_branch"], "bmad/epic-1")

    def test_land_from_inside_the_worktree_merges_into_the_main_tree(self):
        wt = self.start()["path"]
        write(wt, "feature.py", "x = 1\n")
        commit(wt, "feature")
        result, code = land.land(wt, "bmad/epic-1", with_tests=False)
        self.assertEqual(code, 0, result)
        self.assertEqual(result["main_tree"], self.repo)
        self.assertTrue(os.path.isfile(os.path.join(self.repo, "feature.py")))


